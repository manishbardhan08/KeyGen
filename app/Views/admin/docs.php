      <pre class="kg-code">import requests

BASE = "<?= esc($base) ?>/api/v1"

def auth(api_key, license_key, hwid, product):
    r = requests.post(f"{BASE}/auth", json={
        "api_key": api_key, "license_key": license_key,
        "hwid": hwid, "product": product,
    }, timeout=15)

    if r.status_code == 200:
        return r.json()["token"]
    if r.status_code == 503:
        raise RuntimeError(r.json()["message"])            # offline
    raise PermissionError(r.json()["messages"]["error"])   # denied

def validate(token, hwid):
    r = requests.post(f"{BASE}/validate",
                      json={"token": token, "hwid": hwid}, timeout=15)
    return r.status_code == 200, r.json()

def logout(token):
    requests.post(f"{BASE}/logout", json={"token": token}, timeout=15)</pre>

